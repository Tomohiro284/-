  const entries = [];

  // 熟語や活用の一部に紛れ込みやすい語（一文字の漢字・二文字以下の仮名）は
  // 前後の字種を見てから一致させる。
  const KANA_ONLY = /^[ぁ-ゖァ-ヺー]+$/;
  const isFragile = (w) => w.length === 1 || (w.length <= 2 && KANA_ONLY.test(w));

  for (const [a, b, tag, weak] of JA_WORDS) {
    if (!a || !b) continue;
    entries.push({ a, b, type: 'n', tag: tag || 'その他', lang: 'ja', weak: !!weak || isFragile(a) || isFragile(b) });
  }
  for (const [a, b] of JA_I_ADJ) {
    entries.push({ a, b, type: 'i', tag: '形容詞', lang: 'ja' });
  }
  for (const [a, typeA, b, typeB] of JA_VERBS) {
    if (typeB === 'skip' || !b) continue;
    entries.push({ a, b, type: 'v', typeA, typeB, tag: '動詞', lang: 'ja' });
  }
  for (const [a, b, tag] of JA_RAW) {
    entries.push({ a, b, type: 'n', tag: tag || '定型', lang: 'ja', weak: isFragile(a) || isFragile(b) });
  }
  for (const [a, b, opt] of EN_WORDS) {
    entries.push({ a, b, type: 'en', tag: 'English', lang: 'en', opt: opt || {} });
  }

  return { entries };
